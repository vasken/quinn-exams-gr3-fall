import { spellingWords } from "./spelling-words";
import type { Grade, Question, Subject, WordPartsQuestion } from "./types";

type PartKind = "prefix" | "suffix" | "base word";

function wp(word: string, part: string, kind: PartKind, extra: Partial<WordPartsQuestion> = {}): WordPartsQuestion {
  const start = kind === "suffix" ? word.lastIndexOf(part) : word.indexOf(part);
  return {
    id: `wp-${word}-${kind}`,
    type: "wordparts",
    word,
    target: [start, start + part.length],
    prompt: `Tap the letters that make the **${kind}** in “${word}”.`,
    explain: `The ${kind} is “${part}”.`,
    ...extra,
  };
}

function spell(grades: Grade[]): Question[] {
  return spellingWords
    .filter((w) => w.grades.some((g) => grades.includes(g)))
    .map((w) => ({
      id: `spell-${w.word}`,
      type: "typed" as const,
      prompt: `Listen and spell the missing word:\n${w.sentence.replace(w.word, "_____").replace(cap(w.word), "_____")}`,
      say: `${w.word}. ${w.sentence} ${w.word}.`,
      answer: w.word,
      hint: `It starts with “${w.word[0]}” and has ${w.word.length} letters. (Pattern: ${w.pattern})`,
      explain: `It is spelled ${w.word.toUpperCase().split("").join("-")}.`,
      grades: w.grades,
    }));
}

